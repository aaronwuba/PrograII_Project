    private void IngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_IngresarActionPerformed
        String usuario = IngreseSuUsuario.getText();
        String clave = new String(IngreseContraseña.getPassword());
        
        if (usuario.equals("admin")&& clave.equals("4321")){
        
            javax.swing.JOptionPane.showMessageDialog(this, "Bienvenido Administrador");     
            
            MenuAdministrador menu = new MenuAdministrador();
            menu.setVisible(true);
            this.dispose();
            
        } else if (usuario.equals("Trabajador") && clave.equals("8765")) {
            
            javax.swing.JOptionPane.showMessageDialog(this, "Bienvenido Trabajador");
            
            MenuTrabajador menu = new MenuTrabajador();
            menu.setVisible(true);
            this.dispose();
        }else {
        
            javax.swing.JOptionPane.showMessageDialog(this, "Usuario o contraseña incorreta");
            
           
        }
    }//GEN-LAST:event_IngresarActionPerformed

